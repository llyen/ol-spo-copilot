_WORD_RE = re.compile(rf"(?<![A-Za-z0-9_{_PL}])[A-Za-z]+(?![A-Za-z0-9_{_PL}])")


def _match_case(source: str, target: str) -> str:
    if source.isupper() and len(source) > 1:
        return target.upper()
    if source[:1].isupper():
        return target[:1].upper() + target[1:]
    return target


def restore(text: str) -> str:
    """Zwraca tekst z przywroconymi znakami diakrytycznymi."""
    if not text:
        return text
    for src, dst in PHRASES:
        if src in text:
            text = text.replace(src, dst)
        cap = src[:1].upper() + src[1:]
        if cap in text:
            text = text.replace(cap, dst[:1].upper() + dst[1:])

    def sub(m: re.Match[str]) -> str:
        word = m.group(0)
        if word.isupper() and len(word) > 1:
            return word
        target = WORDS.get(word.lower())
        return _match_case(word, target) if target else word

    return _WORD_RE.sub(sub, text)
